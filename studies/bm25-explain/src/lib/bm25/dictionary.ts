function collect(raw: string): Set<string> {
  const set = new Set<string>();
  for (const piece of raw.split(/\s+/)) {
    const w = piece.trim();
    if (w.length >= 2) set.add(w);
  }
  return set;
}

export const ZH_DICT = collect(RAW);

export const ZH_MAX_LEN = [...ZH_DICT].reduce((m, w) => Math.max(m, w.length), 4);
